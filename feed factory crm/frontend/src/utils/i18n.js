let currentLang = 'ar';

export const t = (key, params) => {
  if (!key) return '';
  const keys = key.split('.');
  let value = translations[currentLang];
  if (!value) return key;
  for (const k of keys) {
    if (value && typeof value === 'object' && k in value) {
      value = value[k];
    } else {
      return key;
    }
  }
  if (typeof value === 'string' && params) {
    return value.replace(/\{(\w+)\}/g, (_, k) => params[k] || '');
  }
  return typeof value === 'string' ? value : key;
};

export const init = (lang) => {
  // Arabic is the hard default for this system. The language toggle UI has
  // been removed from Settings (role-based access only, single language for
  // now). We deliberately ignore any stored 'en' preference here so existing
  // users aren't stuck on English with no way to switch back. English support
  // remains fully implemented in this file for future re-enablement — just
  // not currently reachable from the UI.
  currentLang = 'ar';
  try { const { applyDirection } = require('../utils/formatters'); applyDirection('ar'); } catch(e) {}
};

export const getLang = () => currentLang;

export const setLang = (lang) => {
  currentLang = lang;
  if (typeof window !== 'undefined') {
    localStorage.setItem('lang', lang);
    try {
      const { applyDirection } = require('../utils/formatters');
      applyDirection(lang);
    } catch(e) {}
  }
};

export const isRTL = () => currentLang === 'ar';

export const setDirection = (lang) => {
  try {
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
    document.documentElement.lang = lang;
  } catch(e) {}
};
